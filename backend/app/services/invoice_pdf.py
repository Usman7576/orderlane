"""Invoice PDF rendering with ReportLab. Pure: data in, PDF bytes out."""

from dataclasses import dataclass
from datetime import datetime
from decimal import Decimal
from io import BytesIO
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle


@dataclass(frozen=True)
class InvoiceLine:
    name: str
    qty: Decimal
    unit: str
    unit_price: Decimal
    total: Decimal


@dataclass(frozen=True)
class InvoiceData:
    number: str
    order_number: int
    issued_at: datetime
    business_name: str
    customer_name: str
    currency: str
    lines: list[InvoiceLine]
    total: Decimal
    previous_balance: Decimal

    @property
    def new_balance(self) -> Decimal:
        return self.previous_balance + self.total


def _money(amount: Decimal, currency: str) -> str:
    return f"{currency} {amount:,.0f}"


def _qty(qty: Decimal) -> str:
    return f"{qty.normalize():f}"


def render_invoice(data: InvoiceData) -> bytes:
    buffer = BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm,
        title=f"Invoice {data.number}",
        author=data.business_name,
    )
    styles = getSampleStyleSheet()
    small = ParagraphStyle("small", parent=styles["Normal"], fontSize=8, textColor=colors.grey)
    brand = ParagraphStyle("brand", parent=styles["Title"], alignment=0, fontSize=18, leading=22)
    money = lambda amount: _money(amount, data.currency)  # noqa: E731

    header = Table(
        [
            [
                Paragraph(f"<b>{escape(data.business_name)}</b>", brand),
                Paragraph(
                    f"<b>INVOICE</b><br/>{data.number}<br/>Order #{data.order_number}<br/>"
                    f"{data.issued_at:%d %b %Y, %H:%M}",
                    styles["Normal"],
                ),
            ]
        ],
        colWidths=[110 * mm, 64 * mm],
    )
    header.setStyle(
        TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"), ("ALIGN", (1, 0), (1, 0), "RIGHT")])
    )

    rows = [["Item", "Qty", "Unit", "Unit price", "Amount"]]
    rows += [
        [
            Paragraph(escape(line.name), styles["Normal"]),
            _qty(line.qty),
            line.unit,
            money(line.unit_price),
            money(line.total),
        ]
        for line in data.lines
    ]
    rows += [
        ["", "", "", "Total", money(data.total)],
        ["", "", "", "Previous balance", money(data.previous_balance)],
        ["", "", "", "Balance due", money(data.new_balance)],
    ]
    items = Table(rows, colWidths=[78 * mm, 16 * mm, 18 * mm, 32 * mm, 30 * mm], repeatRows=1)
    last = len(rows) - 1
    items.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1f2937")),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("ALIGN", (1, 0), (-1, -1), "RIGHT"),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("LINEBELOW", (0, 1), (-1, last - 3), 0.25, colors.HexColor("#e5e7eb")),
                ("LINEABOVE", (3, last - 2), (-1, last - 2), 0.75, colors.black),
                ("FONTNAME", (3, last), (-1, last), "Helvetica-Bold"),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
            ]
        )
    )

    story = [
        header,
        Spacer(1, 8 * mm),
        Paragraph(f"<b>Bill to:</b> {escape(data.customer_name)}", styles["Normal"]),
        Spacer(1, 6 * mm),
        items,
        Spacer(1, 10 * mm),
        Paragraph(
            "Generated by OrderLane from a confirmed WhatsApp order. "
            "Demo data: prices and businesses are illustrative.",
            small,
        ),
    ]
    doc.build(story)
    return buffer.getvalue()
